import {mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {skills} from './catalog.mjs';
import {activities} from './exercises.mjs';
import {flashcards} from './flashcards.mjs';
import {skillChecks} from './skill-checks.mjs';
import {drills} from './drills.mjs';
const root=fileURLToPath(new URL('.',import.meta.url));
if(new Set(skills.map(s=>s.id)).size!==skills.length)throw new Error('Every skill needs a unique, permanent ID.');
for(const a of activities)if(!skills.some(s=>s.id===a.skill&&s.activity===a.id))throw new Error('Activity has no matching skill: '+a.id);
for(const s of skills)if(!s.activity&&!skillChecks[s.id])throw new Error('Missing practice for '+s.id);
if(new Set(flashcards.map(c=>c.id)).size!==flashcards.length)throw new Error('Duplicate flashcard IDs');
for(const c of flashcards)if(!skills.some(s=>s.id===c.skill)||!c.prompt||(!c.answer&&!c.answerCode))throw new Error('Invalid flashcard: '+c.id);
for(const d of drills)if(!skills.some(s=>s.id===d.skill))throw new Error('Code drill has no matching skill: '+d.id);
if(new Set(drills.map(d=>d.id)).size!==drills.length)throw new Error('Duplicate code drill IDs');
await mkdir(join(root,'dist'),{recursive:true});
for(const name of ['index.html','styles.css','app.mjs','catalog.mjs','schedule.mjs','flashcards.mjs','flashcard-ui.mjs','exercises.mjs','python-worker.mjs','skill-checks.mjs','activity-client.mjs','activity-config.mjs','drills.mjs','drill-data.mjs','drill-ui.mjs','drill-worker.mjs'])await copyFile(join(root,name),join(root,'dist',name));
console.log('Built practice studio: 57 directly accessible skills, 54 quick checks, 9 interactive examples, '+drills.length+' code drills.');
